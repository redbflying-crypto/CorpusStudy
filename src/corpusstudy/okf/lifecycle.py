"""Concept lifecycle: create, edit, review and deprecate, each logged in `log.md`.

    new        draft skeleton for a type (status: draft, generated by the drafter)
    touch      content changed: new `generated` stamp; a stable concept returns to draft
    verify     human sign-off: append `verified: human:<id>`, set status stable
    deprecate  keep for links and history, no longer current

`verify` is the human review gate (OKF trust tier "human-reviewed"). It refuses a concept
that would not pass the producer profile once stamped, and only accepts `human:` actors.
"""

from __future__ import annotations

from datetime import UTC, datetime
from pathlib import Path

from corpusstudy.okf import document
from corpusstudy.okf.bundle import Bundle, Concept, Issue, load_bundle, parse_meta
from corpusstudy.okf.indexes import add_log_entry, write_indexes
from corpusstudy.okf.models import Status, actor_kind
from corpusstudy.okf.profile import TYPES, check_concept

# Body sections each concept type starts with (OKF section 4.2 favours structure).
TEMPLATES: dict[str, list[str]] = {
    "Bible Book": ["Overview", "Setting", "Outline", "Themes", "Key passages"],
    "Theme": ["Overview", "Development through Scripture", "Reformed view", "Key passages"],
    "Person": ["Summary", "Life", "Significance", "Key passages"],
    "Doctrine": ["Definition", "Reformed view", "Where other traditions differ", "Key passages"],
    "Event": ["Summary", "Context", "Significance", "Key passages"],
    "Parable": ["Summary", "Setting", "Meaning", "Interpretive notes", "Key passages"],
}


class LifecycleError(ValueError):
    def __init__(self, message: str, issues: list[Issue] | None = None):
        super().__init__(message)
        self.issues = issues or []


def _now() -> datetime:
    return datetime.now(UTC).replace(microsecond=0)


def _get(bundle: Bundle, concept_id: str) -> Concept:
    concept_id = concept_id.removesuffix(".md").lstrip("/")
    if concept_id not in bundle.concepts:
        raise LifecycleError(f"no concept {concept_id!r} in {bundle.root}")
    return bundle.concepts[concept_id]


def _write(c: Concept, raw: dict) -> None:
    c.path.write_text(document.render(raw, c.body), encoding="utf-8")


def _link(c: Concept) -> str:
    return f"[{c.title}](/{c.id}.md)"


def new_concept(
    root: str | Path, type_: str, slug: str, title: str, *, by: str, now: datetime | None = None
) -> Path:
    if type_ not in TEMPLATES:
        raise LifecycleError(f"type must be one of {sorted(TEMPLATES)}")
    if actor_kind(by) == "unknown":
        raise LifecycleError(f"{by!r} is not an OKF actor")
    path = Path(root) / TYPES[type_] / f"{slug}.md"
    if path.exists():
        raise LifecycleError(f"{path} already exists")
    meta = {
        "type": type_,
        "title": title,
        "description": "",
        "tags": [],
        "status": Status.DRAFT.value,
        "generated": {"by": by, "at": now or _now()},
        "sources": [],
        "title_fr": "",
        "aliases": [],
        "key_passages": [],
        "tradition": "reformed",
    }
    body = "\n\n".join(f"# {section}\n" for section in TEMPLATES[type_])
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(document.render(meta, body), encoding="utf-8")
    add_log_entry(root, "Creation", f"Drafted [{title}](/{TYPES[type_]}/{slug}.md).")
    write_indexes(root)
    return path


def touch(root: str | Path, concept_id: str, *, by: str, now: datetime | None = None) -> Concept:
    """Record a content change. A reviewed concept goes back to draft until re-reviewed."""
    if actor_kind(by) == "unknown":
        raise LifecycleError(f"{by!r} is not an OKF actor")
    bundle = load_bundle(root)
    c = _get(bundle, concept_id)
    raw = dict(c.raw)
    raw["generated"] = {"by": by, "at": now or _now()}
    if raw.get("status", Status.STABLE) == Status.STABLE and c.meta.type != "Reference":
        raw["status"] = Status.DRAFT.value
    _write(c, raw)
    add_log_entry(root, "Update", f"Edited {_link(c)}; awaiting review.")
    write_indexes(root)
    return c


def verify(root: str | Path, concept_id: str, *, by: str, now: datetime | None = None) -> Concept:
    """Stamp a human review. Refuses when the stamped concept would fail the profile."""
    if actor_kind(by) != "human":
        raise LifecycleError(f"only a person can review: use human:<id>, not {by!r}")
    bundle = load_bundle(root)
    c = _get(bundle, concept_id)
    if c.meta.lifecycle == Status.DEPRECATED:
        raise LifecycleError(f"{c.id} is deprecated")
    raw = dict(c.raw)
    previous = raw.get("verified") or []
    previous = [previous] if isinstance(previous, dict) else list(previous)
    raw["verified"] = [*previous, {"by": by, "at": now or _now()}]
    raw["status"] = Status.STABLE.value

    # Check the concept exactly as it will be written.
    candidate_text = document.render(raw, c.body)
    meta, body = document.split(candidate_text)
    parsed = parse_meta(meta or {}, f"{c.id}.md", [])  # same tolerant parse as the loader
    if parsed is None:
        raise LifecycleError(f"{c.id}: frontmatter unreadable after stamping")
    candidate = Concept(c.id, c.path, parsed, meta or {}, body, document.links(body, c.id))
    errors = [i for i in check_concept(candidate, bundle) if i.level == "error"]
    if errors:
        raise LifecycleError(f"{c.id} is not ready for review sign-off", errors)

    c.path.write_text(candidate_text, encoding="utf-8")
    add_log_entry(root, "Review", f"{_link(c)} reviewed and verified by {by}.")
    write_indexes(root)
    return candidate


def deprecate(root: str | Path, concept_id: str, reason: str) -> Concept:
    bundle = load_bundle(root)
    c = _get(bundle, concept_id)
    raw = dict(c.raw)
    raw["status"] = Status.DEPRECATED.value
    _write(c, raw)
    add_log_entry(root, "Deprecation", f"{_link(c)}: {reason}")
    write_indexes(root)
    return c
