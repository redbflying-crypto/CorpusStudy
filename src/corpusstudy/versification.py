"""Per-translation verse numbering, and mapping references between KJV and LSG 1910.

The tables are generated by the Phase 2 pipeline and committed under `resources/versification`,
so references can be checked without the downloaded corpus.

KJV and LSG 1910 number about 150 chapters differently: LSG counts most psalm titles as verses
(Ps 51:1-2 is the title, so KJV Ps 51:1 is LSG Ps 51:3), follows the Hebrew chapter breaks in
places (Exod 8, Job 38-41, Song 7...) and splits or joins a few verses (Mark 9:50 / 9:50-51).
"""

from __future__ import annotations

import json
from functools import lru_cache
from pathlib import Path

from corpusstudy.canon import BOOKS_BY_OSIS
from corpusstudy.config import Translation
from corpusstudy.schemas import PassageRef, VerseRef

VERSIFICATION_DIR = Path(__file__).resolve().parent / "resources" / "versification"


class Versification:
    def __init__(self, verse_counts: dict[str, list[int]], superscriptions: dict[str, list[int]]):
        self.verse_counts = verse_counts
        self.superscriptions = {b: set(chs) for b, chs in superscriptions.items()}

    def verse_count(self, book: str, chapter: int) -> int:
        counts = self.verse_counts.get(book)
        if counts is None or not 1 <= chapter <= len(counts):
            return 0
        return counts[chapter - 1]

    def has_title(self, book: str, chapter: int) -> bool:
        """True when the chapter has an unnumbered title (verse 0)."""
        return chapter in self.superscriptions.get(book, set())

    def exists(self, ref: VerseRef) -> bool:
        if ref.verse == 0:
            return self.has_title(ref.book, ref.chapter)
        return 1 <= ref.verse <= self.verse_count(ref.book, ref.chapter)

    def check_passage(self, passage: PassageRef) -> list[str]:
        """Problems with a passage in this numbering; empty when it is valid."""
        problems = []
        name = BOOKS_BY_OSIS[passage.book].name_en
        if passage.is_whole_chapter:
            return problems  # chapters are checked by PassageRef against the canon
        for ch, v in (
            (passage.start_chapter, passage.start_verse),
            (passage.end_chapter, passage.end_verse),
        ):
            assert v is not None
            if not self.exists(VerseRef(book=passage.book, chapter=ch, verse=v)):
                count = self.verse_count(passage.book, ch)
                problem = f"{name} {ch} has {count} verses, not {v}"
                if problem not in problems:
                    problems.append(problem)
        return problems

    @property
    def total_verses(self) -> int:
        return sum(sum(c) for c in self.verse_counts.values())


@lru_cache
def versification(translation: Translation) -> Versification:
    data = json.loads((VERSIFICATION_DIR / f"{translation}.json").read_text(encoding="utf-8"))
    return Versification(data["verse_counts"], data.get("superscriptions", {}))


@lru_cache
def _links(src: Translation, dst: Translation) -> dict[str, list[str]]:
    data = json.loads((VERSIFICATION_DIR / "KJV-LSG1910.json").read_text(encoding="utf-8"))
    out: dict[str, list[str]] = {}
    for link in data["links"]:
        for key in link[str(src)]:
            # A many-to-many link maps each source verse to every target verse.
            out[key] = link[str(dst)]
    return out


def map_verse(ref: VerseRef, src: Translation, dst: Translation) -> list[VerseRef]:
    """The verse(s) of `dst` that hold the text of `ref` in `src`. Usually exactly one."""
    if src == dst:
        return [ref]
    linked = _links(src, dst).get(ref.osis)
    if linked is not None:
        return [VerseRef.from_osis(k) for k in linked]
    return [ref] if versification(dst).exists(ref) else []


def map_passage(passage: PassageRef, src: Translation, dst: Translation) -> PassageRef:
    """Translate a passage reference from one numbering to the other.

    Whole chapters keep their numbers (only a few verses move across chapter breaks).
    """
    if src == dst or passage.is_whole_chapter:
        return passage
    assert passage.start_verse is not None and passage.end_verse is not None
    start = map_verse(
        VerseRef(book=passage.book, chapter=passage.start_chapter, verse=passage.start_verse),
        src,
        dst,
    )
    end = map_verse(
        VerseRef(book=passage.book, chapter=passage.end_chapter, verse=passage.end_verse),
        src,
        dst,
    )
    if not start or not end:
        raise ValueError(f"{passage.osis} has no counterpart in {dst}")
    first, last = start[0], end[-1]
    return PassageRef(
        book=passage.book,
        start_chapter=first.chapter,
        start_verse=first.verse,
        end_chapter=last.chapter,
        end_verse=last.verse,
    )
